// Runs after `next build`: lists every built script, style and font (cached when the service worker
// installs), and the 3D models, sound effects, campaign map art and card portraits (cached later,
// once the game is idle, so a first visit on a slow connection isn't held up), in
// public/sw-manifest.js, so the whole game works offline after a visit. Music is left out (it's
// large) and is cached as each track plays.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const root = process.cwd();

const walk = dir => readdirSync(dir).flatMap(name => {
  const path = join(dir, name);
  return statSync(path).isDirectory() ? walk(path) : [path];
});

// Public files are served from the site root
const publicUrl = path => `/${relative(join(root, 'public'), path).split(sep).join('/')}`;

const nextStatic = walk(join(root, '.next', 'static'))
  .filter(path => /\.(js|css|woff2?)$/.test(path))
  .map(path => `/_next/static/${relative(join(root, '.next', 'static'), path).split(sep).join('/')}`);
const publicAssets = ['models', 'sounds', 'map', 'cards'].flatMap(dir => walk(join(root, 'public', dir)).map(publicUrl));

const version = readFileSync(join(root, '.next', 'BUILD_ID'), 'utf8').trim();
writeFileSync(
  join(root, 'public', 'sw-manifest.js'),
  `// Generated by scripts/build-sw-manifest.mjs - do not edit\nself.__PRECACHE = ${JSON.stringify({ version, files: nextStatic, later: publicAssets })};\n`
);
console.log(`Service worker manifest: ${nextStatic.length} files, ${publicAssets.length} later (build ${version})`);
